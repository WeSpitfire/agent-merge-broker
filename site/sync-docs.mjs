import { readFile, writeFile, mkdir, rm } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const repo = path.resolve(here, "..");
// An explicit output directory lets tests inspect the rewritten pages without touching the site.
const out = process.argv[2] ? path.resolve(process.argv[2]) : path.join(here, "docs");

const BLOB = "https://github.com/WeSpitfire/agent-merge-broker/blob/main";
const TREE = "https://github.com/WeSpitfire/agent-merge-broker/tree/main";

/** Repo-relative targets that have no page on this site and must point back at GitHub. */
const EXTERNAL = [
  [/\]\(\.\.\/schemas\/([^)]+)\)/g, `](${BLOB}/schemas/$1)`],
  [/\]\(schemas\/\)/g, `](${TREE}/schemas)`],
  [/\]\(examples\/two-agents\/\)/g, `](${TREE}/examples/two-agents)`],
  [/\]\(CONTRIBUTING\.md\)/g, `](${BLOB}/CONTRIBUTING.md)`],
  [/\]\(LICENSE\)/g, `](${BLOB}/LICENSE)`],
];

/** Docs that do have a page here, so cross-references (and their anchors) stay inside the site. */
const SITE_PAGES = {
  GETTING_STARTED: "getting-started",
  ARCHITECTURE: "architecture",
  PROTOCOL: "protocol",
  SECURITY: "security",
  RELEASING: "releasing",
  COMPATIBILITY: "compatibility",
  VISION: "vision",
  ROADMAP: "roadmap",
  SUPPORT: "support",
};
const INTERNAL = [
  [
    new RegExp(`\\]\\((?:docs\\/)?(${Object.keys(SITE_PAGES).join("|")})\\.md(#[^)]+)?\\)`, "g"),
    // VitePress prefixes heading slugs that start with a digit, such as "2. Install", with "_".
    (_match, name, anchor = "") => `](/docs/${SITE_PAGES[name]}${anchor.replace(/^#(\d)/u, "#_$1")})`,
  ],
];

const PAGES = [
  { from: "docs/GETTING_STARTED.md", to: "getting-started.md" },
  { from: "docs/ARCHITECTURE.md", to: "architecture.md" },
  { from: "docs/PROTOCOL.md", to: "protocol.md" },
  { from: "docs/SECURITY.md", to: "security.md" },
  { from: "docs/RELEASING.md", to: "releasing.md" },
  { from: "docs/COMPATIBILITY.md", to: "compatibility.md" },
  { from: "VISION.md", to: "vision.md" },
  { from: "ROADMAP.md", to: "roadmap.md" },
  { from: "SUPPORT.md", to: "support.md" },
];

function rewrite(markdown) {
  return [...EXTERNAL, ...INTERNAL].reduce(
    (text, [pattern, replacement]) => text.replace(pattern, replacement),
    markdown,
  );
}

await rm(out, { recursive: true, force: true });
await mkdir(out, { recursive: true });

for (const page of PAGES) {
  const source = await readFile(path.join(repo, page.from), "utf8");
  const banner =
    "<!-- Generated by site/sync-docs.mjs. Edit " + page.from + " at the repository root. -->\n\n";
  await writeFile(path.join(out, page.to), banner + rewrite(source), "utf8");
}

console.log(`synced ${PAGES.length} documents from the repository root`);
